"""The fee calculation must match the deployed n8n workflow exactly.

``tests/fixtures/reference_cases.json`` is generated by running the real Code
node bodies out of the exported workflow JSON. See docs/BACKGROUND.md.
Comparing against it turns "faithful port" into a checked property.

The tests cover the published fee table and the rules behind it, so a regression
is reported in the club's own vocabulary rather than as an opaque fixture diff.
"""

import json
from pathlib import Path

import pytest

from clubops.domain.fee import (
    billable_months,
    calculate_fee,
    format_euro,
    format_period,
    months_remaining_in_term,
    resolve_start_month,
    round2,
)
from clubops.domain.models import CivilDate, FeeConfig
from clubops.domain.timestamps import parse_timestamp

FIXTURE = Path(__file__).parent.parent / "fixtures" / "reference_cases.json"
REFERENCE_CASES = json.loads(FIXTURE.read_text())["cases"]


def _quote_for(case):
    registered_on = parse_timestamp(case["row"]["Timestamp"])
    return calculate_fee(registered_on)


@pytest.mark.parametrize("case", REFERENCE_CASES, ids=lambda c: c["label"])
def test_matches_deployed_n8n_output(case):
    """Every numeric and textual field the n8n node produced, reproduced."""
    expected = case["quote"]
    actual = _quote_for(case)

    assert actual.start_year == expected["startYear"]
    assert actual.start_month == expected["startMonth"]
    assert actual.start_month_name == expected["startMonthName"]
    assert actual.months == expected["months"]
    assert actual.period == expected["period"]
    assert actual.shifted == expected["shifted"]
    assert actual.membership_fee_standard == expected["membershipFeeStandard"]
    assert actual.membership_fee_reduced == expected["membershipFeeReduced"]
    assert actual.total_standard == expected["totalStandard"]
    assert actual.total_reduced == expected["totalReduced"]
    assert actual.calculation_line == expected["calculationLine"]


